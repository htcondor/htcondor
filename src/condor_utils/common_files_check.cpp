// The fields of the ClassAds in the wire format.  Nothing outside this
// file should know these names.
static const char * const FIELD_INTERNAL_NAME = "InternalName";
static const char * const FIELD_NAME = ATTR_NAME;
static const char * const FIELD_ORDERED = "Ordered";
static const char * const FIELD_SORTED = "Sorted";
static const char * const FIELD_JOB_ID = "JobId";
static const char * const FIELD_STAGED_ORDERED = "StagedOrdered";
static const char * const FIELD_STAGED_SORTED = "StagedSorted";
static const char * const FIELD_STAGED_JOB_ID = "StagedJobId";


ListOfCatalogs
getCommonInputCatalogsBySimpleName( const ClassAd & jobAd ) {
	// This must match how the catalog names are generated by
	// computeCommonInputFileCatalogs() and computeCommonInputFiles().
	ListOfCatalogs catalogs;

	std::string commonInputCatalogs;
	jobAd.LookupString( ATTR_COMMON_INPUT_CATALOGS, commonInputCatalogs );
	for( const auto & name : StringTokenIterator(commonInputCatalogs) ) {
		std::string contents;
		jobAd.LookupString( "_x_catalog_" + name, contents );
		catalogs.emplace_back( name, contents );
	}

	std::string commonInputFiles;
	if( jobAd.LookupString( ATTR_COMMON_INPUT_FILES, commonInputFiles ) ) {
		auto r = determineCIFScopeAndType( jobAd );
		if(! r) { return {}; }
		auto [scope, type] = * r;
		std::string default_name;
		formatstr( default_name, "%s_%s", type.c_str(), scope.c_str() );
		catalogs.emplace_back( default_name, commonInputFiles );
	}

	return catalogs;
}


static std::string
getCommonFilesIwd( const ClassAd & jobAd ) {
	// We must resolve relative paths exactly as the transfer will, and both
	// staging (UniShadow::before_common_file_transfer()) and fallback
	// transfer use the job's Iwd.  Don't use SUBMIT_Iwd for spooled jobs:
	// it names a directory on the submit machine, which may not exist on
	// the AP.  (As of this writing, spooling doesn't upload common files
	// at all, so spooled jobs with relative common files can't run anyway.
	// If that changes, note that each proc's spooled Iwd differs, so
	// per-proc copies of common files wouldn't hash the same.)
	std::string iwd;
	jobAd.LookupString( ATTR_JOB_IWD, iwd );
	return iwd;
}


// Describe what transferring `entry` would put in the sandbox.
static std::string
canonicalizeCommonFile( const std::string & entry, const std::string & iwd ) {
	if( IsUrl(entry.c_str()) ) {
		return entry;
	}

	// A trailing slash means "transfer the directory's contents" rather than
	// "transfer the directory," but canonicalization would remove it.
	std::string path = entry;
	bool trailing_slash = false;
	while( path.size() > 1 && (path.back() == '/' || path.back() == DIR_DELIM_CHAR) ) {
		path.pop_back();
		trailing_slash = true;
	}

	std::filesystem::path p(path);
	if(! fullpath(path.c_str()) && ! iwd.empty()) {
		p = std::filesystem::path(iwd) / p;
	}

	// Where the entry lands in the sandbox must match how staging transfers
	// it.  UniShadow::before_common_file_transfer() doesn't pass the job's
	// PreserveRelativePaths to its FileTransfer, so staged catalogs are
	// always flattened: an entry lands under the last component of its
	// path *as listed* (not as resolved), whatever directories precede it.
	// So "dir/a" from x and "a" from x/dir are the same, and so are "link/a"
	// and "dir/a" through a symlinked directory, but "b" as a symlink to "a"
	// is not.  If staging ever honors PreserveRelativePaths, this must
	// change with it: relative entries would land at their (normalized)
	// relative paths, and the setting would have to be part of the hash.
	//
	// An entry with a trailing slash puts the directory's contents in the
	// sandbox's top level, so its own name doesn't matter: "link/" and "dir/"
	// are the same.  (See FileTransfer::ExpandFileTransferList().)
	std::string destination = trailing_slash ? "./" : std::filesystem::path(path).filename().string();

	// If the file (or the IWD) is gone, deliberately don't match anything
	// staged while it existed: the job should go on hold rather than run
	// with files its submitter may have replaced or removed.
	std::error_code ec;
	std::filesystem::path canonical = std::filesystem::canonical( p, ec );
	std::string source;
	if( ec ) {
		source = "unresolvable:" + p.lexically_normal().string();
	} else {
		source = canonical.string();
	}

	std::string description;
	formatstr( description, "%s%s -> %s", source.c_str(), trailing_slash ? "/" : "", destination.c_str() );
	return description;
}


std::optional<CommonFilesHashes>
hashCommonFiles( const std::string & commonFiles, const std::string & iwd ) {
	std::vector<std::string> entries;
	for( const auto & entry : StringTokenIterator(commonFiles, ",") ) {
		entries.push_back( canonicalizeCommonFile( entry, iwd ) );
	}

	CommonFilesHashes hashes;
	hashes.description = join( entries, ", " );

	// Paths can't contain NUL, so use it as the separator.
	std::string ordered;
	for( const auto & e : entries ) { ordered += e; ordered += '\0'; }

	std::ranges::sort( entries );
	std::string sorted;
	for( const auto & e : entries ) { sorted += e; sorted += '\0'; }

	if(! compute_sha256_checksum( ordered, hashes.ordered ) ||
		! compute_sha256_checksum( sorted, hashes.sorted )) {
		return std::nullopt;
	}
	return hashes;
}


