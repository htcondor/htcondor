static classad::ClassAd *
lookupNestedAd( const classad::ClassAd & ad, const std::string & attr ) {
	return dynamic_cast<classad::ClassAd *>( ad.Lookup( attr ) );
}


void
addStagedCatalogsReport(
	ClassAd & cmdAd, const ClassAd & jobAd,
	const ListOfCatalogs & stagedCatalogs,
	const std::map<std::string, std::string> & internalToSimpleNameMap
) {
	// The report is keyed by internal name, so the schedd knows which
	// staged copy these hashes describe.  Internal names aren't valid
	// attribute names, so the report is a list.
	std::vector<ExprTree *> report;
	std::string iwd = getCommonFilesIwd( jobAd );
	for( const auto & [internalName, contents] : stagedCatalogs ) {
		auto name = internalToSimpleNameMap.find( internalName );
		auto hashes = hashCommonFiles( contents, iwd );
		if( name == internalToSimpleNameMap.end() || ! hashes ) {
			// Jobs mapping this copy will be held, because the schedd
			// will have no record of what it contains.
			dprintf( D_ERROR, "Failed to hash staged catalog %s, not reporting it.\n", internalName.c_str() );
			continue;
		}

		ClassAd * entry = new ClassAd();
		entry->InsertAttr( FIELD_INTERNAL_NAME, internalName );
		entry->InsertAttr( FIELD_NAME, name->second );
		entry->InsertAttr( FIELD_ORDERED, hashes->ordered );
		entry->InsertAttr( FIELD_SORTED, hashes->sorted );
		report.push_back( entry );
	}
	cmdAd.Insert( ATTR_STAGED_CATALOG_HASHES, classad::ExprList::MakeExprList( report ) );
}


std::optional<std::vector<StagedCatalogReport>>
parseStagedCatalogsReport( const ClassAd & cmdAd ) {
	auto * list = dynamic_cast<classad::ExprList *>( cmdAd.Lookup( ATTR_STAGED_CATALOG_HASHES ) );
	if( list == nullptr ) { return std::nullopt; }

	std::vector<StagedCatalogReport> reports;
	for( auto * expr : * list ) {
		auto * entry = dynamic_cast<classad::ClassAd *>( expr );
		if( entry == nullptr ) { continue; }

		StagedCatalogReport r;
		entry->LookupString( FIELD_INTERNAL_NAME, r.internalName );
		entry->LookupString( FIELD_NAME, r.name );
		entry->LookupString( FIELD_ORDERED, r.ordered );
		entry->LookupString( FIELD_SORTED, r.sorted );
		if( r.internalName.empty() || r.name.empty() || r.ordered.empty() || r.sorted.empty() ) {
			dprintf( D_ALWAYS, "Ignoring incomplete staged catalog report for '%s'.\n", r.internalName.c_str() );
			continue;
		}
		reports.push_back( r );
	}
	return reports;
}


CommonFilesScopeRecord
parseScopeRecord( const ClassAd & scopeClusterAd ) {
	CommonFilesScopeRecord record;
	auto * ad = lookupNestedAd( scopeClusterAd, ATTR_COMMON_FILES_SCOPE_HASHES );
	if( ad == nullptr ) { return record; }

	for( const auto & [name, expr] : * ad ) {
		auto * entry = dynamic_cast<classad::ClassAd *>( expr );
		if( entry == nullptr ) { continue; }

		CommonFilesFingerprint f;
		entry->LookupString( FIELD_ORDERED, f.ordered );
		entry->LookupString( FIELD_SORTED, f.sorted );
		entry->LookupString( FIELD_JOB_ID, f.jobId );
		record[name] = f;
	}
	return record;
}


std::string
unparseScopeRecord( const CommonFilesScopeRecord & record ) {
	classad::ClassAd ad;
	for( const auto & [name, f] : record ) {
		ClassAd * entry = new ClassAd();
		entry->InsertAttr( FIELD_ORDERED, f.ordered );
		entry->InsertAttr( FIELD_SORTED, f.sorted );
		entry->InsertAttr( FIELD_JOB_ID, f.jobId );
		ad.Insert( name, entry );
	}

	std::string value;
	classad::ClassAdUnParser unparser;
	unparser.Unparse( value, & ad );
	return value;
}


void
insertExpectations(
	ClassAd & shadowJobAd,
	const std::map<std::string, CommonFilesExpectation> & expectations
) {
	// Always insert the attribute, even if it's empty; a job shadow treats
	// any catalog without an entry as unverifiable.
	ClassAd * ad = new ClassAd();
	for( const auto & [name, e] : expectations ) {
		ClassAd * entry = new ClassAd();
		if( e.scope ) {
			entry->InsertAttr( FIELD_ORDERED, e.scope->ordered );
			entry->InsertAttr( FIELD_SORTED, e.scope->sorted );
			entry->InsertAttr( FIELD_JOB_ID, e.scope->jobId );
		}
		if( e.staged ) {
			entry->InsertAttr( FIELD_STAGED_ORDERED, e.staged->ordered );
			entry->InsertAttr( FIELD_STAGED_SORTED, e.staged->sorted );
			entry->InsertAttr( FIELD_STAGED_JOB_ID, e.staged->jobId );
		}
		ad->Insert( name, entry );
	}
	shadowJobAd.Insert( ATTR_COMMON_FILES_HASH_CHECK, ad );
}


static std::map<std::string, CommonFilesExpectation>
parseExpectations( const ClassAd & shadowJobAd ) {
	std::map<std::string, CommonFilesExpectation> expectations;
	auto * ad = lookupNestedAd( shadowJobAd, ATTR_COMMON_FILES_HASH_CHECK );
	if( ad == nullptr ) { return expectations; }

	for( const auto & [name, expr] : * ad ) {
		auto * entry = dynamic_cast<classad::ClassAd *>( expr );
		if( entry == nullptr ) { continue; }

		CommonFilesExpectation e;
		CommonFilesFingerprint f;
		if( entry->LookupString( FIELD_ORDERED, f.ordered ) ) {
			entry->LookupString( FIELD_SORTED, f.sorted );
			entry->LookupString( FIELD_JOB_ID, f.jobId );
			e.scope = f;
		}
		f = {};
		if( entry->LookupString( FIELD_STAGED_ORDERED, f.ordered ) ) {
			entry->LookupString( FIELD_STAGED_SORTED, f.sorted );
			entry->LookupString( FIELD_STAGED_JOB_ID, f.jobId );
			e.staged = f;
		}
		expectations[name] = e;
	}
	return expectations;
}


