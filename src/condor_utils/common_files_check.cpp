// Hold reasons shouldn't be arbitrarily long.
static std::string
truncateForHoldReason( std::string s ) {
	const size_t max_length = 512;
	if( s.size() > max_length ) {
		s.resize( max_length );
		s += "...";
	}
	return s;
}


std::optional<CommonFilesVerifier::Failure>
CommonFilesVerifier::verify() const {
	bool staging = (m_role == Role::TransferShadow);

	// Fail closed: never stage or map common files we can't verify.
	auto unverified = []( const std::string & why ) {
		return Failure{
			"Could not verify this job's common input files, so not starting it: " + why,
			COMMON_FILES_MISMATCH_SUB_CODE::Unverified
		};
	};

	auto r = determineCIFScopeAndType( m_jobAd );
	if(! r) { return unverified( "could not determine the job's cluster or DAG." ); }
	auto [scope, type] = * r;
	bool is_dag = (type == ATTR_DAGMAN_JOB_ID);
	const char * scope_name = is_dag ? "DAG" : "cluster";

	auto catalogs = getCommonInputCatalogsBySimpleName( m_jobAd );
	if( catalogs.empty() ) { return unverified( "could not determine the job's catalogs." ); }

	auto expectations = parseExpectations( m_jobAd );
	std::string iwd = getCommonFilesIwd( m_jobAd );
	for( const auto & [name, contents] : catalogs ) {
		auto it = expectations.find( name );
		const CommonFilesExpectation * e = (it == expectations.end()) ? nullptr : & it->second;

		// A transfer shadow is about to stage its own copy, but a job shadow
		// will map a copy someone else staged, so it must know what that
		// copy contains.  It might not if, for instance, the transfer shadow
		// couldn't hash it, or was too old to report it.
		if( ! staging && (e == nullptr || ! e->staged) ) {
			return unverified( "the schedd has no record of the contents of the staged copy of catalog '" + name + "'." );
		}

		auto hashes = hashCommonFiles( contents, iwd );
		if(! hashes) {
			return unverified( "failed to hash catalog '" + name + "'." );
		}
		std::string files = truncateForHoldReason( hashes->description );

		// The first catalog with this name staged in the scope sets the rule.
		// If there isn't one yet, this transfer shadow will set it.  If the
		// scope has no cluster ad (e.g., the DAGMan job has left the queue),
		// the schedd can't record one, and a job shadow is only checked
		// against the staged copy, below.
		if( e != nullptr && e->scope && hashes->ordered != e->scope->ordered ) {
			bool only_order = (hashes->sorted == e->scope->sorted);
			int subcode = 0;
			if( is_dag ) {
				subcode = only_order ? COMMON_FILES_MISMATCH_SUB_CODE::DAGOrder : COMMON_FILES_MISMATCH_SUB_CODE::DAG;
			} else {
				subcode = only_order ? COMMON_FILES_MISMATCH_SUB_CODE::ClusterOrder : COMMON_FILES_MISMATCH_SUB_CODE::Cluster;
			}

			std::string reason;
			formatstr( reason,
				"Common input files for catalog '%s' %s those of job %s in the same %s (%s %s); "
				"every job in a %s must list the same files in the same order.  This job's files: %s",
				name.c_str(),
				only_order ? "are listed in a different order than" : "do not match",
				e->scope->jobId.c_str(), scope_name, type.c_str(), scope.c_str(),
				scope_name, files.c_str()
			);
			return Failure{ reason, subcode };
		}

		// Even if this job agrees with the rest of its scope, the copy it
		// would map might not: see "Why check against the staged copy as
		// well as the scope?" in common_files_check.h.
		if( ! staging && hashes->ordered != e->staged->ordered ) {
			std::string reason;
			formatstr( reason,
				"Common input files for catalog '%s' do not match those staged for job %s in the same %s (%s %s); "
				"every job in a %s must list the same files in the same order.  This job's files: %s",
				name.c_str(), e->staged->jobId.c_str(), scope_name, type.c_str(), scope.c_str(),
				scope_name, files.c_str()
			);
			return Failure{ reason,
				is_dag ? COMMON_FILES_MISMATCH_SUB_CODE::DAG : COMMON_FILES_MISMATCH_SUB_CODE::Cluster };
		}

		std::string matched;
		if( ! staging ) { matched = "the copy staged for job " + e->staged->jobId; }
		if( e != nullptr && e->scope ) {
			if(! matched.empty()) { matched += " and "; }
			matched += "the first in its scope, job " + e->scope->jobId;
		}
		dprintf( D_FULLDEBUG, "CommonFilesVerifier: catalog '%s' %s.\n", name.c_str(),
			matched.empty() ? "is the first in its scope" : ("matches " + matched).c_str() );
	}

	return std::nullopt;
}
